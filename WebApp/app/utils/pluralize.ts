/**
 * Функция для склонения существительных после числительных.
 *
 * @param count - Число, по которому подбирается форма
 * @param forms - Массив из трех форм слова: [1, 2-4, 5+]
 * @returns Строка с правильной формой слова
 */

export function pluralize(
  count: number,
  forms: [string, string, string],
): string {
  // Приводим к абсолютному значению на случай отрицательных чисел
  const absCount = Math.abs(count);

  // Находим остаток от деления на 100 и на 10
  const mod100 = absCount % 100;
  const mod10 = absCount % 10;

  // Исключение: числа, оканчивающиеся на 11-14
  if (mod100 >= 11 && mod100 <= 14) {
    return forms[2]; // 'кейсов'
  }

  // Оканчивается на 1 (кроме 11)
  if (mod10 === 1) {
    return forms[0]; // 'кейс'
  }

  // Оканчивается на 2, 3, 4 (кроме 12, 13, 14)
  if (mod10 >= 2 && mod10 <= 4) {
    return forms[1]; // 'кейса'
  }

  // Все остальные случаи (5-9, 0)
  return forms[2]; // 'кейсов'
}
